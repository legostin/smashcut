import fs from 'node:fs';
import path from 'node:path';
import { SKILLS_DIR, USER_SKILLS_DIR, GALLERY_DIR } from './config.ts';
import { copyDir } from './util.ts';

export interface SkillInfo { name: string; description: string; origin: 'builtin' | 'user'; path: string }

function parseFront(md: string) {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(md);
  const front: Record<string, string> = {};
  if (m) for (const line of m[1].split('\n')) { const i = line.indexOf(':'); if (i > 0) front[line.slice(0, i).trim()] = line.slice(i + 1).trim(); }
  return { front, body: m ? md.slice(m[0].length) : md };
}

export function listSkills(): SkillInfo[] {
  const out: SkillInfo[] = [];
  for (const [origin, base] of [['builtin', SKILLS_DIR], ['user', USER_SKILLS_DIR]] as const) {
    if (!fs.existsSync(base)) continue;
    for (const e of fs.readdirSync(base, { withFileTypes: true })) {
      const f = path.join(base, e.name, 'SKILL.md');
      if (!e.isDirectory() || !fs.existsSync(f)) continue;
      const { front } = parseFront(fs.readFileSync(f, 'utf8'));
      out.push({ name: front.name || e.name, description: front.description || '', origin, path: f });
    }
  }
  return out;
}

const BEGIN = '<!-- studio:begin (generated by Smashcut — edits inside are overwritten) -->';
const END = '<!-- studio:end -->';

function upsertBlock(file: string, block: string, title: string) {
  const content = `${BEGIN}\n${block.trim()}\n${END}`;
  if (!fs.existsSync(file)) { fs.writeFileSync(file, `# ${title}\n\n${content}\n\n## Project notes\n\n(Write project-specific notes for agents here.)\n`); return; }
  const cur = fs.readFileSync(file, 'utf8');
  const a = cur.indexOf(BEGIN), b = cur.indexOf(END);
  if (a >= 0 && b > a) fs.writeFileSync(file, cur.slice(0, a) + content + cur.slice(b + END.length));
  else fs.writeFileSync(file, cur.trimEnd() + '\n\n' + content + '\n');
}

/** copy skills into <project>/.claude/skills and write CLAUDE.md / AGENTS.md */
export function syncSkills(projectDir: string, projectName: string) {
  const skills = listSkills();
  const target = path.join(projectDir, '.claude', 'skills');
  fs.mkdirSync(target, { recursive: true });
  for (const s of skills) copyDir(path.dirname(s.path), path.join(target, path.basename(path.dirname(s.path))));
  const intro = `This folder is an **Smashcut** project: a video edit where motion graphics are HTML/CSS/JS clips and music is Tone.js code.
The editor runs at the URL in $STUDIO_URL (default http://127.0.0.1:4317) and gives you the \`studio\` MCP server: render frames of your own work and LOOK at them, read/resolve frame comments, edit the timeline, render & analyse music.

Layout: \`project.json\` (timeline — prefer the MCP timeline tools), \`clips/<id>/\` (clip packages), \`music/<id>/score.js\` (music), \`media/\` (imported footage — never modify), \`.studio/\` (cache — never edit), \`comments.json\` (use MCP tools).
Built-in templates: ${GALLERY_DIR}/clips and /music (copy via MCP \`use_template\`).

Golden rules:
0. Script first: \`get_script\`; if it has no scenes, write it with \`set_script\` before any other work (see the studio-production skill).
1. A clip is a pure function of time — read the clip authoring skill before writing one.
2. After every change, render frames (\`render_clip\` / \`render_frame\`) and look at them; iterate until it is genuinely good.
3. When you work on comments, call \`resolve_comment\` for each one you addressed, with a one-line note.`;
  const list = skills.map((s) => `- **${s.name}** — ${s.description} (\`.claude/skills/${path.basename(path.dirname(s.path))}/SKILL.md\`)`).join('\n');
  upsertBlock(path.join(projectDir, 'CLAUDE.md'), `${intro}\n\nSkills (read the relevant ones before working):\n${list}`, projectName);
  const bodies = skills.map((s) => { const { body } = parseFront(fs.readFileSync(s.path, 'utf8')); return `\n---\n\n## Skill: ${s.name}\n\n${body.trim()}\n`; }).join('');
  upsertBlock(path.join(projectDir, 'AGENTS.md'), `${intro}\n${bodies}`, projectName);
}
